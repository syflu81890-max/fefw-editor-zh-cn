def _clean(s):
    return re.sub(r"\\s*\\+\\s*\\d+$", "", str(s or "")).strip()

def item_name(meta):
    en = _clean(meta.get("en"))
    jp = _clean(meta.get("jp"))
    base = ITEMS.get(en) or ITEMS.get(jp)
    if base:
        m = re.search(r"\\+(\\d+)$", str(meta.get("jp") or ""))
        return base + (" +" + m.group(1) if m else "")
    # 未收录词条宁可显示英文，也不把日文原名直接塞进中文界面
    return en or jp or "未知道具"

def class_name(meta):
    en = _clean(meta.get("en"))
    jp = str(meta.get("jp") or "").replace("JID_", "")
    return CLASSES.get(en) or CLASSES.get(jp) or en or jp or "未知兵种"

def unit_name(meta):
    name = str(meta.get("name") or "")
    return CHARACTERS.get(name) or name or str(meta.get("pid") or "未知角色")

